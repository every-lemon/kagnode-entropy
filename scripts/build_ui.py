#!/usr/bin/env python3
"""Render canonical Core templates and verified locally served assets; no network."""

import base64
import hashlib
import json
from pathlib import Path
import re
import os
import subprocess

ROOT = Path(__file__).resolve().parents[1]
CORE = ROOT / "vendor/core"
manifest = json.loads((CORE / "core-manifest.json").read_text())
bundle = json.loads((CORE / "bundle.json").read_text())
subprocess.run(
    [
        "openssl",
        "pkeyutl",
        "-verify",
        "-pubin",
        "-inkey",
        str(CORE / "release-public.pem"),
        "-rawin",
        "-in",
        str(CORE / "core-manifest.json"),
        "-sigfile",
        str(CORE / "core-manifest.sig"),
    ],
    check=True,
    capture_output=True,
    timeout=10,
)
VERSION = manifest["version"]
assert VERSION == bundle["version"] and re.fullmatch(r"5\.0\.[0-9]+", VERSION)
assert manifest["source_commit"] == bundle["source_commit"]
templates = json.loads((CORE / "templates.json").read_text())


def render(name, **slots):
    return re.sub(
        r"\{\{([a-z]+)\}\}", lambda match: slots.get(match[1], ""), templates[name]
    )


routes = []
asset_dir = ROOT / "static/core" / VERSION
asset_dir.mkdir(parents=True, exist_ok=True)
for name, record in bundle["files"].items():
    assert re.fullmatch(r"[a-zA-Z0-9_.-]+", name)
    raw = base64.b64decode(record["data"], validate=True)
    assert len(raw) == record["size"] == manifest["files"][name]["size"]
    assert (
        hashlib.sha256(raw).hexdigest()
        == record["sha256"]
        == manifest["files"][name]["sha256"]
    )
    (asset_dir / name).write_bytes(raw)
    mime = (
        "text/javascript; charset=utf-8"
        if name.endswith(".js")
        else "text/css; charset=utf-8"
        if name.endswith(".css")
        else "image/svg+xml"
    )
    routes.append(
        f'"/kagnode-core/{VERSION}/{name}" => Some((include_bytes!("../static/core/{VERSION}/{name}"), "{mime}")),'
    )
(ROOT / "src/core_assets.rs").write_text(
    "// Generated by scripts/build_ui.py from verified Core assets.\npub fn asset(path: &str) -> Option<(&'static [u8], &'static str)> {\nmatch path {\n"
    + "\n".join(routes)
    + "\n_ => None,\n}\n}\n"
)
head = (
    '<meta name="kagnode-core" content=\''
    + json.dumps(
        {"app": "entropy", "version": VERSION, "authenticated": False},
        separators=(",", ":"),
    )
    + "'>"
)
for kind, attr in [
    ("theme", '<script src="{}"></script>'),
    ("style", '<link rel="stylesheet" href="{}">'),
    ("script", '<script src="{}" defer></script>'),
]:
    head += attr.format("/kagnode-core/" + VERSION + "/" + bundle["entrypoints"][kind])
for filename in ["index.html", "admin.html", "link.html"]:
    html = (ROOT / "ui" / filename).read_text().replace("</head>", head + "</head>")
    if filename in {"admin.html", "link.html"}:
        content = '<form id="admin-login-form"><label for="credential">Administrator key</label><input id="credential" type="password" required autocomplete="current-password" maxlength="128"><button type="submit"><span data-core-icon="lock"></span>Sign in</button></form><p id="login-message" role="status" hidden></p>'
        provider = '<button type="button" data-core-login-provider hidden><span data-core-icon="account"></span>Login with KagNode</button><p data-core-login-status role="status"></p>'
        frame = render(
            "login-frame",
            product="KagNode. Entropy",
            heading="Sign in",
            description="Manage your local Entropy service.",
            content=content,
            provider=provider,
        ).replace("<main data-core-login", '<main id="admin-login" data-core-login', 1)
        if filename == "admin.html":
            # Availability is server-authorized at runtime. Keep the entire
            # optional row hidden until enabled, rather than an empty divider.
            html = html.replace(
                "{{login}}",
                frame.replace(
                    '<div class="kn-core-login-provider">',
                    '<div class="kn-core-login-provider" hidden>',
                    1,
                ),
            )
        if filename == "link.html":
            html = html.replace(
                "{{login}}",
                frame.replace('id="admin-login"', 'id="admin-link"')
                .replace(
                    "Manage your local Entropy service.",
                    "Confirm your local administrator key, then approve your KagNode Account.",
                )
                .replace(
                    '<button type="submit"><span data-core-icon="lock"></span>Sign in</button>',
                    "",
                )
                .replace("data-core-login-provider hidden", "data-core-login-provider")
                .replace("Login with KagNode", "Connect KagNode Account"),
            )
        nav = '<nav class="sidebar-nav"><a href="/admin" aria-current="page"><span data-core-icon="observability"></span><span class="nav-label">Overview</span></a><a href="#client-form"><span data-core-icon="key"></span><span class="nav-label">Client access</span></a><a href="#account-settings"><span data-core-icon="account"></span><span class="nav-label">Account</span></a><a href="/"><span data-core-icon="flask"></span><span class="nav-label">API explorer</span></a></nav>'
        sidebar = render(
            "sidebar",
            brand='<a class="brand" href="/admin"><img src="/brand/favicon.svg" width="32" height="32" alt=""><span class="brand-copy"><strong>KagNode.</strong><small>Entropy</small></span></a>',
            navigation=nav,
            footer="",
        )
        html = html.replace("{{sidebar}}", sidebar)
    if filename == "admin.html":
        menu = render(
            "account-menu",
            identity='<strong id="owner-name">Local administrator</strong><small id="owner-email"></small>',
            actions='<a href="#account-settings"><span data-core-icon="account"></span>Account settings</a><button id="signout" type="button"><span data-core-icon="lock"></span>Sign out</button>',
        )
        html = html.replace(
            "{{account}}",
            '<button data-account-menu aria-label="Account"><span class="avatar"><img id="owner-photo" alt="" hidden><span id="owner-initial">E</span></span></button>'
            + menu,
        )
    (ROOT / "static" / filename).write_text(html)
lock = {
    "schema": 1,
    "app": "entropy",
    "repository": "every-lemon/kagnode-core",
    "baseline": VERSION,
    "adapter_version": VERSION,
    "backend_updates": "reviewed",
    "fallback_version": VERSION,
    "ui_patch_range": "5.0.x",
    "source_commit": manifest["source_commit"],
    "fallback_manifest_sha256": hashlib.sha256(
        (CORE / "core-manifest.json").read_bytes()
    ).hexdigest(),
    "runtime": "embedded verified assets; Rust adapter changes require reviewed rebuild",
    "source_files": {
        str(p.relative_to(CORE)): hashlib.sha256(p.read_bytes()).hexdigest()
        for p in sorted(CORE.rglob("*"))
        if p.is_file()
    },
}
(ROOT / "core.lock.json").write_text(json.dumps(lock, indent=2) + "\n")
print(
    f"Verified Core {VERSION} assets and rendered shared authentication/sidebar templates."
)

subprocess.run(
    [os.environ.get("RUSTFMT", "rustfmt"), str(ROOT / "src/core_assets.rs")], check=True
)
